using System;
using System.Collections.Generic;
using System.Text;
using Resonate.Tools.Schemac.Schema;

namespace Resonate.Tools.Schemac.Emit;

/* The managed mirror of the storage family: one sequential struct per storage
   type in the module's C# namespace, the frozen layout as constants, and a
   generated check tying the two together. Managed code reads a chunk through a
   pointer and a Span; nothing crosses by marshaling. */
internal static class CSharpEmitter
{
    internal static string Render(ModuleUnit module)
    {
        StringBuilder text = new();
        text.Append("// Generated by schemac ").Append(Schemac.Version).Append(" from ");
        for (int index = 0; index < module.Files.Count; ++index)
        {
            text.Append(index == 0 ? "" : ", ").Append(PathText.Relative(module.Files[index].Path));
        }
        text.Append("; do not edit.\n\n");
        text.Append("using System;\n");
        text.Append("using System.Runtime.InteropServices;\n");
        text.Append("using Resonate.CSharp;\n\n");
        text.Append("namespace ").Append(NamespaceOf(module.Id)).Append(";\n");

        List<TypeDecl> storage = [];
        foreach (TypeDecl type in module.Types)
        {
            /* Enums and bitmasks are chunk scalars, not structs: fields of one
               appear as the width's primitive type, so a managed view of the
               named type would be an empty struct with the wrong size. */
            if (type.IsStorage && type.Kind != TypeKind.Enum && type.Kind != TypeKind.Bitmask)
            {
                storage.Add(type);
            }
        }

        foreach (TypeDecl type in storage)
        {
            text.Append("\n/* A view borrows the chunk it describes; the analyzer keeps it "
                        + "out of fields. */\n");
            text.Append("[ResonateView]\n[StructLayout(LayoutKind.Sequential)]\n");
            text.Append("public struct ").Append(type.Name).Append("\n{\n");
            foreach (FieldDecl field in type.Fields)
            {
                text.Append("    public ").Append(FieldType(field, module)).Append(' ')
                    .Append(FieldName(type, field)).Append(";\n");
            }
            text.Append("\n    public const string SchemaName = \"").Append(type.QualifiedName)
                .Append("\";\n");
            text.Append("    public static ReadOnlySpan<byte> SchemaNameUtf8 => \"")
                .Append(type.QualifiedName).Append("\"u8;\n");
            text.Append("}\n\n");
            text.Append("public static class ").Append(type.Name).Append("Layout\n{\n");
            text.Append("    public const int Size = ").Append(type.Layout!.Size).Append(";\n");
            foreach (FieldDecl field in type.Fields)
            {
                text.Append("    public const int ").Append(FieldName(type, field))
                    .Append("Offset = ").Append(field.Offset).Append(";\n");
            }
            text.Append("}\n");
        }

        /* The check compares the runtime layout with the schema's frozen
           offsets, so a compiler that packs differently fails a test instead
           of corrupting the boundary. */
        text.Append("\npublic static class LayoutChecks\n{\n");
        text.Append("    public static bool Verify()\n    {\n");
        foreach (TypeDecl type in storage)
        {
            text.Append("        if (Marshal.SizeOf<").Append(type.Name).Append(">() != ")
                .Append(type.Name).Append("Layout.Size");
            foreach (FieldDecl field in type.Fields)
            {
                string pascal = FieldName(type, field);
                text.Append("\n            || Marshal.OffsetOf<").Append(type.Name)
                    .Append(">(nameof(").Append(type.Name).Append('.').Append(pascal)
                    .Append(")) != ").Append(type.Name).Append("Layout.").Append(pascal)
                    .Append("Offset");
            }
            text.Append(")\n        {\n            return false;\n        }\n");
        }
        text.Append("        return true;\n    }\n}\n");
        return text.ToString();
    }

    /* The core math mirrors a chunk can hold; emitted once when any module
       uses one. Field order matches resonate/core/math.h. */
    internal static string RenderMath()
    {
        return """
            // Generated by schemac; the managed mirrors of the core math types.
            using System.Runtime.InteropServices;

            namespace Resonate.CSharp.Math;

            [StructLayout(LayoutKind.Sequential)]
            public struct Vec2
            {
                public float X;
                public float Y;
            }

            [StructLayout(LayoutKind.Sequential)]
            public struct Vec3
            {
                public float X;
                public float Y;
                public float Z;
            }

            [StructLayout(LayoutKind.Sequential)]
            public struct Vec4
            {
                public float X;
                public float Y;
                public float Z;
                public float W;
            }

            [StructLayout(LayoutKind.Sequential)]
            public struct Quat
            {
                public float X;
                public float Y;
                public float Z;
                public float W;
            }

            [StructLayout(LayoutKind.Sequential)]
            public struct Mat4
            {
                public float M00;
                public float M01;
                public float M02;
                public float M03;
                public float M10;
                public float M11;
                public float M12;
                public float M13;
                public float M20;
                public float M21;
                public float M22;
                public float M23;
                public float M30;
                public float M31;
                public float M32;
                public float M33;
            }

            """;
    }

    internal static bool UsesMath(IReadOnlyList<ModuleUnit> modules)
    {
        foreach (ModuleUnit module in modules)
        {
            foreach (TypeDecl type in module.Types)
            {
                if (!type.IsStorage)
                {
                    continue;
                }
                foreach (FieldDecl field in type.Fields)
                {
                    if (field.Primitive?.Kind == PrimitiveKind.Math)
                    {
                        return true;
                    }
                }
            }
        }
        return false;
    }

    /* resonate.render -> Resonate.Render, which is also the file stem. */
    internal static string NamespaceOf(string module_id)
    {
        string[] segments = module_id.Split('.');
        for (int index = 0; index < segments.Length; ++index)
        {
            segments[index] = char.ToUpperInvariant(segments[index][0]) +
                              segments[index].Substring(1);
        }
        return string.Join('.', segments);
    }

    private static string FieldType(FieldDecl field, ModuleUnit module)
    {
        if (field.Primitive is Primitive primitive)
        {
            return PrimitiveType(primitive);
        }

        TypeDecl resolved = field.Resolved!;
        if (resolved.Kind == TypeKind.Enum || resolved.Kind == TypeKind.Bitmask)
        {
            /* The chunk holds the enum's width, not a C# enum; the values stay
               on the authored side for now. */
            return PrimitiveType(Primitives.Find(resolved.Width)!);
        }
        return resolved.Module == module.Id
                   ? resolved.Name
                   : NamespaceOf(resolved.Module) + '.' + resolved.Name;
    }

    private static string PrimitiveType(Primitive primitive)
    {
        switch (primitive.Kind)
        {
            case PrimitiveKind.Integer:
                return primitive.Name switch
                {
                    "i8" => "sbyte",
                    "u8" => "byte",
                    "i16" => "short",
                    "u16" => "ushort",
                    "i32" => "int",
                    "u32" => "uint",
                    "i64" => "long",
                    "u64" => "ulong",
                    _ => throw new InvalidOperationException(primitive.Name),
                };
            case PrimitiveKind.Float:
                return primitive.Name == "f32" ? "float" : "double";
            case PrimitiveKind.Boolean:
                /* The chunk stores one byte; C# bool marshals as four. */
                return "byte";
            case PrimitiveKind.Entity:
                return "Resonate.CSharp.Bindings.EntityHandle";
            case PrimitiveKind.Blob:
                return "Resonate.CSharp.Bindings.BlobHandle";
            case PrimitiveKind.Math:
                return primitive.Name switch
                {
                    "vec2" => "Resonate.CSharp.Math.Vec2",
                    "vec3" => "Resonate.CSharp.Math.Vec3",
                    "vec4" => "Resonate.CSharp.Math.Vec4",
                    "quat" => "Resonate.CSharp.Math.Quat",
                    "mat4" => "Resonate.CSharp.Math.Mat4",
                    _ => throw new InvalidOperationException(primitive.Name),
                };
            default:
                throw new InvalidOperationException(primitive.Name);
        }
    }

    /* A member cannot be named like its enclosing type, which Parent.parent
       would become; the view keeps the meaning and adds the suffix. */
    private static string FieldName(TypeDecl type, FieldDecl field)
    {
        string name = PascalCase(field.Name);
        return name == type.Name ? name + "Value" : name;
    }

    /* fov_y_degrees -> FovYDegrees. */
    private static string PascalCase(string name)
    {
        StringBuilder builder = new(name.Length);
        bool upper = true;
        foreach (char character in name)
        {
            if (character == '_')
            {
                upper = true;
                continue;
            }
            builder.Append(upper ? char.ToUpperInvariant(character) : character);
            upper = false;
        }
        return builder.ToString();
    }
}
