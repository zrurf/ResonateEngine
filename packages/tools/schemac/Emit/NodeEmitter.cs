using System;
using System.Collections.Generic;
using System.Text;
using Resonate.Tools.Schemac.Schema;

namespace Resonate.Tools.Schemac.Emit;

/* The document-side counterpart of the storage emitters: the node types'
   compositions, exposed fields, component names and field layouts a document
   adapter can resolve. The tables are plain data; the DOM parser and domain
   adapters read them without knowing any vocabulary of their own. */
internal static class NodeEmitter
{
    internal static string Render(ModuleUnit module)
    {
        StringBuilder text = new();
        text.Append("// Generated by schemac ").Append(Schemac.Version)
            .Append("; node type compositions for ").Append(module.Id)
            .Append(", do not edit.\n\n");
        string guard = Guard(module.Id);
        text.Append("#ifndef ").Append(guard).Append('\n');
        text.Append("#define ").Append(guard).Append("\n\n");
        text.Append("#include <cstddef>\n");
        text.Append("#include <iterator>\n");
        text.Append("#include <resonate/dom/schema.h>\n");
        text.Append("\n#include \"").Append(module.Id).Append("/components.gen.h\"\n\n");
        text.Append("namespace ").Append(Namespace(module.Id)).Append("::generated\n{\n");

        List<TypeDecl> nodes = [];
        List<TypeDecl> components = [];
        Dictionary<string, TypeDecl> enums = new(StringComparer.Ordinal);
        foreach (TypeDecl type in module.Types)
        {
            if (type.Kind == TypeKind.Node)
            {
                nodes.Add(type);
            }
            else if (type.Kind == TypeKind.Component)
            {
                components.Add(type);
            }
            else if (type.Kind == TypeKind.Enum)
            {
                enums[type.Name] = type;
            }
        }

        foreach (TypeDecl node in nodes)
        {
            List<FieldDecl> authoring = [];
            foreach (FieldDecl field in node.Fields)
            {
                if (field.Authoring)
                {
                    authoring.Add(field);
                }
            }
            if (authoring.Count > 0)
            {
                text.Append("\ninline constexpr dom::AuthoringField k").Append(node.Name)
                    .Append("Authoring[] = {\n");
                foreach (FieldDecl field in authoring)
                {
                    text.Append("    {\"").Append(field.Name).Append("\", \"")
                        .Append(field.TypeName).Append("\"},\n");
                }
                text.Append("};\n");
            }

            for (int index = 0; index < node.Uses.Count; ++index)
            {
                NodeUse use = node.Uses[index];
                if (use.Exposed.Count == 0)
                {
                    continue;
                }
                text.Append("\ninline constexpr dom::ExposedField k").Append(node.Name)
                    .Append("Use").Append(index).Append("Exposed[] = {\n");
                foreach (string field in use.Exposed)
                {
                    text.Append("    {\"").Append(field).Append("\", \"").Append(use.Component)
                        .Append("\", \"").Append(field).Append("\"},\n");
                }
                text.Append("};\n");
            }

            if (node.Uses.Count > 0)
            {
                text.Append("\ninline constexpr dom::UsedComponent k").Append(node.Name)
                    .Append("Uses[] = {\n");
                for (int index = 0; index < node.Uses.Count; ++index)
                {
                    NodeUse use = node.Uses[index];
                    text.Append("    {\"").Append(use.Component).Append("\", ");
                    if (use.Exposed.Count == 0)
                    {
                        text.Append("resonate::Span<const dom::ExposedField>{}");
                    }
                    else
                    {
                        text.Append("resonate::Span<const dom::ExposedField>(k").Append(node.Name)
                            .Append("Use").Append(index).Append("Exposed, std::size(k")
                            .Append(node.Name).Append("Use").Append(index)
                            .Append("Exposed))");
                    }
                    text.Append("},\n");
                }
                text.Append("};\n");
            }
        }

        if (nodes.Count == 0)
        {
            text.Append("\ninline constexpr dom::NodeTypeDesc kNodeTypes[1] = {};\n");
            text.Append("inline constexpr std::size_t kNodeTypeCount = 0U;\n");
        }
        else
        {
            text.Append("\ninline constexpr dom::NodeTypeDesc kNodeTypes[] = {\n");
            foreach (TypeDecl node in nodes)
            {
                List<FieldDecl> authoring = [];
                foreach (FieldDecl field in node.Fields)
                {
                    if (field.Authoring)
                    {
                        authoring.Add(field);
                    }
                }
                text.Append("    {\"").Append(node.Name).Append("\", \"").Append(node.QualifiedName)
                    .Append("\", ");
                if (node.Uses.Count == 0)
                {
                    text.Append("resonate::Span<const dom::UsedComponent>{}");
                }
                else
                {
                    text.Append("resonate::Span<const dom::UsedComponent>(k").Append(node.Name)
                        .Append("Uses, std::size(k").Append(node.Name).Append("Uses))");
                }
                text.Append(", ");
                if (authoring.Count == 0)
                {
                    text.Append("resonate::Span<const dom::AuthoringField>{}");
                }
                else
                {
                    text.Append("resonate::Span<const dom::AuthoringField>(k").Append(node.Name)
                        .Append("Authoring, std::size(k").Append(node.Name).Append("Authoring))");
                }
                text.Append("},\n");
            }
            text.Append("};\n");
            text.Append("inline constexpr std::size_t kNodeTypeCount = std::size(kNodeTypes);\n");
        }

        foreach (TypeDecl component in components)
        {
            /* The schema declares each migration step with a typed output; the
               thunk adapts it to the generic pointer a loader's registry
               carries. Taking the thunk's address is what requires the owning
               module's definition. */
            string qualified = component.QualifiedName.Replace(".", "::");
            string space = qualified[..qualified.LastIndexOf("::", StringComparison.Ordinal)];
            foreach (MigrationDecl migration in component.Migrations)
            {
                text.Append("\ninline bool k").Append(component.Name).Append("MigrateFrom")
                    .Append(migration.From)
                    .Append("(const void* payload, std::size_t size, void* out)\n{\n    return ::")
                    .Append(space).Append("::migrate").Append(component.Name).Append("From")
                    .Append(migration.From).Append("(payload, size, *static_cast<::")
                    .Append(qualified).Append("*>(out));\n}\n");
            }
            if (component.Migrations.Count > 0)
            {
                text.Append("\ninline constexpr dom::ComponentMigrationDesc k")
                    .Append(component.Name).Append("Migrations[] = {\n");
                foreach (MigrationDecl migration in component.Migrations)
                {
                    text.Append("    {").Append(migration.From).Append("U, ")
                        .Append(migration.To).Append("U, &k").Append(component.Name)
                        .Append("MigrateFrom").Append(migration.From).Append("},\n");
                }
                text.Append("};\n");
            }
            if (component.Fields.Count == 0)
            {
                continue;
            }
            /* An enum-typed field carries its value names, so a document can
               author the identifier instead of a bare number. */
            foreach (FieldDecl field in component.Fields)
            {
                if (!enums.TryGetValue(field.TypeName, out TypeDecl? enumType))
                {
                    continue;
                }
                text.Append("\ninline constexpr const char* const k").Append(component.Name)
                    .Append('_').Append(field.Name).Append("Enum[] = {\n");
                foreach (EnumValueDecl value in enumType.Values)
                {
                    text.Append("    \"").Append(value.Name).Append("\",\n");
                }
                text.Append("};\n");
            }
            text.Append("\ninline constexpr dom::ComponentFieldDesc k").Append(component.Name)
                .Append("Fields[] = {\n");
            foreach (FieldDecl field in component.Fields)
            {
                text.Append("    {\"").Append(field.Name).Append("\", \"")
                    .Append(field.TypeName).Append("\", ").Append(field.Offset)
                    .Append("U, ").Append(field.Size).Append("U, ");
                if (enums.TryGetValue(field.TypeName, out TypeDecl? enumType))
                {
                    text.Append('k').Append(component.Name).Append('_').Append(field.Name)
                        .Append("Enum, static_cast<std::uint32_t>(std::size(k")
                        .Append(component.Name).Append('_').Append(field.Name).Append("Enum))");
                }
                else
                {
                    text.Append("nullptr, 0U");
                }
                text.Append("},\n");
            }
            text.Append("};\n");
        }

        if (components.Count == 0)
        {
            text.Append("\ninline constexpr dom::ComponentDesc kComponentDescs[1] = {};\n");
            text.Append("inline constexpr std::size_t kComponentDescCount = 0U;\n");
        }
        else
        {
            text.Append("\ninline constexpr dom::ComponentDesc kComponentDescs[] = {\n");
            foreach (TypeDecl component in components)
            {
                Layout layout = component.Layout!;
                text.Append("    {\"").Append(component.Name).Append("\", \"")
                    .Append(component.QualifiedName).Append("\", ").Append(layout.Size)
                    .Append("U, ").Append(layout.Align).Append("U, ")
                    .Append(component.Derived ? 1 : 0).Append("U, ");
                if (component.Fields.Count == 0)
                {
                    text.Append("resonate::Span<const dom::ComponentFieldDesc>{}");
                }
                else
                {
                    text.Append("resonate::Span<const dom::ComponentFieldDesc>(k")
                        .Append(component.Name).Append("Fields, std::size(k")
                        .Append(component.Name).Append("Fields))");
                }
                text.Append(", static_cast<const void*>(&k").Append(component.Name)
                    .Append("Defaults), ").Append(component.Version).Append("U},\n");
            }
            text.Append("};\n");
            text.Append("inline constexpr std::size_t kComponentDescCount = ")
                .Append("std::size(kComponentDescs);\n");
        }

        if (components.Count == 0)
        {
            text.Append("\ninline constexpr const char* kComponents[1] = {};\n");
            text.Append("inline constexpr std::size_t kComponentCount = 0U;\n");
        }
        else
        {
            text.Append("\ninline constexpr const char* kComponents[] = {\n");
            foreach (TypeDecl component in components)
            {
                text.Append("    \"").Append(component.Name).Append("\",\n");
            }
            text.Append("};\n");
            text.Append("inline constexpr std::size_t kComponentCount = std::size(kComponents);\n");
        }

        text.Append("\n} // namespace ").Append(Namespace(module.Id)).Append("::generated\n");
        text.Append("\n#endif /* ").Append(guard).Append(" */\n");
        return text.ToString();
    }

    private static string Namespace(string module)
    {
        return module.Replace(".", "::");
    }

    private static string Guard(string module)
    {
        return "RESONATE_GEN_" + module.ToUpperInvariant().Replace('.', '_') + "_NODES_GEN_H";
    }
}
