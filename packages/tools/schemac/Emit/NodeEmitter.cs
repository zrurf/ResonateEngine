using System;
using System.Collections.Generic;
using System.Text;
using Resonate.Tools.Schemac.Schema;

namespace Resonate.Tools.Schemac.Emit;

/* The document-side counterpart of the storage emitters: the node types'
   compositions, exposed fields and the component names a document adapter can
   resolve. The tables are plain data; the DOM parser and domain adapters read
   them without knowing any vocabulary of their own. */
internal static class NodeEmitter
{
    internal static string Render(ModuleUnit module)
    {
        StringBuilder text = new();
        text.Append("// Generated by schemac ").Append(Schemac.Version)
            .Append("; node type compositions for ").Append(module.Id)
            .Append(", do not edit.\n\n");
        string guard = Guard(module.Id);
        text.Append("#ifndef ").Append(guard).Append('\n');
        text.Append("#define ").Append(guard).Append("\n\n");
        text.Append("#include <cstddef>\n");
        text.Append("#include <iterator>\n");
        text.Append("#include <resonate/dom/schema.h>\n\n");
        text.Append("namespace ").Append(Namespace(module.Id)).Append("::generated\n{\n");

        List<TypeDecl> nodes = [];
        List<TypeDecl> components = [];
        foreach (TypeDecl type in module.Types)
        {
            if (type.Kind == TypeKind.Node)
            {
                nodes.Add(type);
            }
            else if (type.Kind == TypeKind.Component)
            {
                components.Add(type);
            }
        }

        foreach (TypeDecl node in nodes)
        {
            for (int index = 0; index < node.Uses.Count; ++index)
            {
                NodeUse use = node.Uses[index];
                if (use.Exposed.Count == 0)
                {
                    continue;
                }
                text.Append("\ninline constexpr dom::ExposedField k").Append(node.Name)
                    .Append("Use").Append(index).Append("Exposed[] = {\n");
                foreach (string field in use.Exposed)
                {
                    text.Append("    {\"").Append(field).Append("\", \"").Append(use.Component)
                        .Append("\", \"").Append(field).Append("\"},\n");
                }
                text.Append("};\n");
            }

            if (node.Uses.Count > 0)
            {
                text.Append("\ninline constexpr dom::UsedComponent k").Append(node.Name)
                    .Append("Uses[] = {\n");
                for (int index = 0; index < node.Uses.Count; ++index)
                {
                    NodeUse use = node.Uses[index];
                    text.Append("    {\"").Append(use.Component).Append("\", ");
                    if (use.Exposed.Count == 0)
                    {
                        text.Append("resonate::Span<const dom::ExposedField>{}");
                    }
                    else
                    {
                        text.Append("resonate::Span<const dom::ExposedField>(k").Append(node.Name)
                            .Append("Use").Append(index).Append("Exposed, std::size(k")
                            .Append(node.Name).Append("Use").Append(index)
                            .Append("Exposed))");
                    }
                    text.Append("},\n");
                }
                text.Append("};\n");
            }
        }

        if (nodes.Count == 0)
        {
            text.Append("\ninline constexpr dom::NodeTypeDesc kNodeTypes[1] = {};\n");
            text.Append("inline constexpr std::size_t kNodeTypeCount = 0U;\n");
        }
        else
        {
            text.Append("\ninline constexpr dom::NodeTypeDesc kNodeTypes[] = {\n");
            foreach (TypeDecl node in nodes)
            {
                text.Append("    {\"").Append(node.Name).Append("\", \"").Append(node.QualifiedName)
                    .Append("\", ");
                if (node.Uses.Count == 0)
                {
                    text.Append("resonate::Span<const dom::UsedComponent>{}");
                }
                else
                {
                    text.Append("resonate::Span<const dom::UsedComponent>(k").Append(node.Name)
                        .Append("Uses, std::size(k").Append(node.Name).Append("Uses))");
                }
                text.Append("},\n");
            }
            text.Append("};\n");
            text.Append("inline constexpr std::size_t kNodeTypeCount = std::size(kNodeTypes);\n");
        }

        if (components.Count == 0)
        {
            text.Append("\ninline constexpr const char* kComponents[1] = {};\n");
            text.Append("inline constexpr std::size_t kComponentCount = 0U;\n");
        }
        else
        {
            text.Append("\ninline constexpr const char* kComponents[] = {\n");
            foreach (TypeDecl component in components)
            {
                text.Append("    \"").Append(component.Name).Append("\",\n");
            }
            text.Append("};\n");
            text.Append("inline constexpr std::size_t kComponentCount = std::size(kComponents);\n");
        }

        text.Append("\n} // namespace ").Append(Namespace(module.Id)).Append("::generated\n");
        text.Append("\n#endif /* ").Append(guard).Append(" */\n");
        return text.ToString();
    }

    private static string Namespace(string module)
    {
        return module.Replace(".", "::");
    }

    private static string Guard(string module)
    {
        return "RESONATE_GEN_" + module.ToUpperInvariant().Replace('.', '_') + "_NODES_GEN_H";
    }
}
